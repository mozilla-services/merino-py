def get_en_gb_seasonal_prior_multiplier(at: datetime | None = None) -> float:
    """Return the GB seasonal prior multiplier for a UTC 10-minute bucket."""
    if at is None:
        at = datetime.now(tz=timezone.utc)
    elif at.tzinfo is None:
        at = at.replace(tzinfo=timezone.utc)
    else:
        at = at.astimezone(timezone.utc)

    minute_since_midnight_utc = at.hour * 60 + at.minute
    bucket = minute_since_midnight_utc // EN_GB_SEASONAL_PRIOR_GRID_MINUTES
    return EN_GB_SEASONAL_PRIOR_MULTIPLIERS_UTC[bucket]
